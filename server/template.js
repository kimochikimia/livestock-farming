// Байгаа тохиргоог дарж бичихгүй: давхардах боломжгүй хүснэгтэд INSERT IGNORE,
// төллөлт / тэжээлийн төлөвлөгөөг зөвхөн хоосон бол нэмнэ
async function applyTemplate(c, farmId) {
  const added = {};
  const count = (k, n) => { added[k] = (added[k] || 0) + n; };
  for (const [species, rows] of Object.entries(CLASSES)) {
    for (const [age_name, age, sex, tw] of rows) {
      count('animal_classes', (await c.run('INSERT IGNORE INTO animal_classes(farm_id, species, age_name, age, sex, target_weight) VALUES(?, ?, ?, ?, ?, ?)',
        [farmId, species, age_name, age, sex, tw ?? null])).changes);
    }
  }
  for (const name of FEEDS) count('feeds', (await c.run('INSERT IGNORE INTO feeds(farm_id, name) VALUES(?, ?)', [farmId, name])).changes);
  for (const name of EXPENSE_TYPES) count('expense_types', (await c.run('INSERT IGNORE INTO expense_types(farm_id, name) VALUES(?, ?)', [farmId, name])).changes);
  for (const [name, na] of TASK_TYPES) count('task_types', (await c.run('INSERT IGNORE INTO task_types(farm_id, name, needs_animals) VALUES(?, ?, ?)', [farmId, name, na])).changes);
  if (!(await c.one('SELECT 1 x FROM breeding WHERE farm_id = ? LIMIT 1', [farmId]))) {
    for (const r of BREEDING) count('breeding', (await c.run('INSERT INTO breeding(farm_id, species, dam_name, births_per_year, gestation, breeding_months, birthing_months) VALUES(?, ?, ?, ?, ?, ?, ?)', [farmId, ...r])).changes);
  }
  if (!(await c.one('SELECT 1 x FROM feed_plan WHERE farm_id = ? LIMIT 1', [farmId]))) {
    for (const r of FEED_PLAN) count('feed_plan', (await c.run('INSERT INTO feed_plan(farm_id, feed_name, kg_1_14, kg_15_30, kg_31_90, price) VALUES(?, ?, ?, ?, ?, ?)', [farmId, ...r])).changes);
  }
  for (const [k, v] of Object.entries(SETTINGS)) {
    await c.run('INSERT IGNORE INTO farm_settings(farm_id, skey, value) VALUES(?, ?, ?)', [farmId, k, v]);
  }
  return added;
}

